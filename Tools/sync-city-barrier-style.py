"""Generate the shared Unity constants from the project-owned Gatefall style manifest."""
import argparse
import hashlib
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / 'Docs/Design/city-barrier-ui-20261106/tokens.json'
OUTPUT = ROOT / 'Assets/Scripts/Presentation/GatefallUiStyle.Generated.cs'


def generate():
    raw = MANIFEST.read_bytes()
    data = json.loads(raw.decode('utf-8-sig'))
    tokens = data['tokens']

    def resolve(key, chain=()):
        if key in chain:
            raise ValueError('Token cycle: ' + key)
        value = tokens[key]['value']
        match = re.fullmatch(r'\{([^{}]+)\}', value) if isinstance(value, str) else None
        return resolve(match.group(1), (*chain, key)) if match else value

    lines = [
        '// Generated by Tools/sync-city-barrier-style.py. Edit the project tokens.json, then regenerate.',
        'using UnityEngine;', '', 'namespace Gatefall', '{', '    public static class GatefallUiStyle', '    {',
        '        public const string StyleId = ' + json.dumps(data['styleId']) + ';',
        '        public const string StyleVersion = ' + json.dumps(data['version']) + ';',
        '        public const string ManifestSha256 = "' + hashlib.sha256(raw).hexdigest() + '";'
    ]
    names = set()
    for key, token in tokens.items():
        name = ''.join(part[:1].upper() + part[1:] for part in key.split('.'))
        if name in names:
            raise ValueError('Generated field collision: ' + name)
        names.add(name)
        value = resolve(key)
        if token['type'] == 'color':
            if not re.fullmatch(r'#[0-9A-Fa-f]{6}', value):
                raise ValueError('Invalid color: ' + key)
            channels = ', '.join(f'{int(value[i:i+2], 16)}f / 255f' for i in (1, 3, 5))
            code = 'public static readonly Color ' + name + ' = new Color(' + channels + ', 1f);'
        elif isinstance(value, str):
            code = 'public const string ' + name + ' = ' + json.dumps(value, ensure_ascii=False) + ';'
        elif type(value) is int:
            code = f'public const int {name} = {value};'
        elif type(value) is float:
            code = f'public const float {name} = {value:g}f;'
        else:
            raise ValueError('Unsupported token: ' + key)
        unit = ' // ' + token['unit'] if 'unit' in token else ''
        lines.append('        ' + code + unit)
    lines += ['    }', '}', '']
    return '\n'.join(lines), len(tokens)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write', action='store_true', help='Regenerate; default only verifies the checked-in output')
    args = parser.parse_args()
    expected, count = generate()
    if args.write:
        OUTPUT.write_text(expected, encoding='utf-8', newline='\n')
    elif not OUTPUT.is_file() or OUTPUT.read_text(encoding='utf-8') != expected:
        raise SystemExit('Style constants differ. Run python Tools/sync-city-barrier-style.py --write')
    print(f'PASS: {count} project-owned Gatefall style tokens match shared Unity constants.')


if __name__ == '__main__':
    main()
